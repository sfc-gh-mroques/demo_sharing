-- =============================================================================
-- load_data.sql
-- Charge les données de démonstration (data/sample/*.csv) dans les tables.
-- À exécuter depuis la racine du projet (les PUT utilisent des chemins relatifs) :
--   snow sql -f setup/load_data.sql --connection <NOM_CONNEXION>
-- =============================================================================

USE ROLE ROUTE_OPTIMIZATION_ROLE;
USE WAREHOUSE ROUTING_WH;
USE SCHEMA FLEET_INTELLIGENCE.ROUTE_OPTIMIZATION;

CREATE STAGE IF NOT EXISTS DATA_LOAD;

PUT file://data/sample/depot.csv @DATA_LOAD/depot AUTO_COMPRESS=FALSE OVERWRITE=TRUE;
PUT file://data/sample/camion.csv @DATA_LOAD/camion AUTO_COMPRESS=FALSE OVERWRITE=TRUE;
PUT file://data/sample/capacite_camion.csv @DATA_LOAD/capacite AUTO_COMPRESS=FALSE OVERWRITE=TRUE;
PUT file://data/sample/commandes.csv @DATA_LOAD/commandes AUTO_COMPRESS=FALSE OVERWRITE=TRUE;

-- Rechargement idempotent
TRUNCATE TABLE IF EXISTS DEPOT;
TRUNCATE TABLE IF EXISTS CAMION;
TRUNCATE TABLE IF EXISTS CAPACITE_CAMION;
TRUNCATE TABLE IF EXISTS COMMANDES;

COPY INTO DEPOT FROM @DATA_LOAD/depot FILE_FORMAT=(TYPE=CSV SKIP_HEADER=1 FIELD_OPTIONALLY_ENCLOSED_BY='"') FORCE=TRUE;
COPY INTO CAMION FROM @DATA_LOAD/camion FILE_FORMAT=(TYPE=CSV SKIP_HEADER=1 FIELD_OPTIONALLY_ENCLOSED_BY='"') FORCE=TRUE;
COPY INTO CAPACITE_CAMION FROM @DATA_LOAD/capacite FILE_FORMAT=(TYPE=CSV SKIP_HEADER=1 FIELD_OPTIONALLY_ENCLOSED_BY='"') FORCE=TRUE;
COPY INTO COMMANDES FROM @DATA_LOAD/commandes FILE_FORMAT=(TYPE=CSV SKIP_HEADER=1 FIELD_OPTIONALLY_ENCLOSED_BY='"' NULL_IF=('')) FORCE=TRUE;

SELECT 'DEPOT' AS T, COUNT(*) AS N FROM DEPOT
UNION ALL SELECT 'CAMION', COUNT(*) FROM CAMION
UNION ALL SELECT 'CAPACITE_CAMION', COUNT(*) FROM CAPACITE_CAMION
UNION ALL SELECT 'COMMANDES', COUNT(*) FROM COMMANDES;
